import 'dotenv/config';
import { configureSdkMitra, runDdlMitra } from 'mitra-sdk';
configureSdkMitra({ baseURL: process.env.MITRA_BASE_URL, token: process.env.MITRA_TOKEN, integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS });
const projectId = Number(process.env.MITRA_PROJECT_ID);
// Status da janela por ANO (RN-07). PRIORIDADE ordena o "beber logo".
const sql = `CREATE OR REPLACE VIEW VW_SAFRAS AS
SELECT b.*, CASE b.STATUS WHEN 'SAINDO' THEN 1 WHEN 'AUGE_FIM' THEN 1 WHEN 'PASSOU' THEN 2 WHEN 'AUGE' THEN 3 WHEN 'JANELA' THEN 4 WHEN 'CEDO' THEN 5 ELSE 6 END AS PRIORIDADE
FROM (
  SELECT s.ID, s.VINHO_ID, v.USUARIO_ID, s.ANO, s.JANELA_INICIO, s.JANELA_AUGE, s.JANELA_FIM,
    COALESCE((SELECT SUM(CASE m.TIPO WHEN 'E' THEN m.QUANTIDADE ELSE -m.QUANTIDADE END) FROM MOVIMENTACOES m WHERE m.SAFRA_ID = s.ID), 0) AS ESTOQUE,
    CASE
      WHEN s.JANELA_INICIO IS NULL OR s.JANELA_AUGE IS NULL OR s.JANELA_FIM IS NULL THEN 'SEM_JANELA'
      WHEN YEAR(CURDATE()) < s.JANELA_INICIO THEN 'CEDO'
      WHEN YEAR(CURDATE()) > s.JANELA_FIM THEN 'PASSOU'
      WHEN YEAR(CURDATE()) = s.JANELA_FIM AND s.JANELA_AUGE = s.JANELA_FIM THEN 'AUGE_FIM'
      WHEN YEAR(CURDATE()) = s.JANELA_FIM THEN 'SAINDO'
      WHEN YEAR(CURDATE()) = s.JANELA_AUGE THEN 'AUGE'
      ELSE 'JANELA'
    END AS STATUS,
    CASE WHEN s.JANELA_FIM IS NULL THEN NULL ELSE CAST(s.JANELA_FIM AS SIGNED) - CAST(YEAR(CURDATE()) AS SIGNED) END AS ANOS_PARA_FIM
  FROM SAFRAS s JOIN VINHOS v ON v.ID = s.VINHO_ID
) b`;
const r = await runDdlMitra({ projectId, sql });
console.log(JSON.stringify(r.result ?? r).slice(0, 150));
